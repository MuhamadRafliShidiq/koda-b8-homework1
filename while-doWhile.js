// Membuat Perulangan While untuk menghasilkan pattern segitiga

let str = "";
let j = 1;
while ( j <= 4 ) {
  str += "*";
  console.log(str);
  j++
};

// Membuat Perulangan Do-While untuk menghasilkan pattern segitiga

let str = "";
let j = 1;
do {
  str += "*";
  console.log(str);
  j++;
} while (j <= 4);


